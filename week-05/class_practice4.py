# Calculating temperature in Celsius to Farenheit

temperature_celsius = 25

temperature_celsius = float(input("Enter the temperature in Celsius: "))

temperature_farenheit = (temperature_celsius * 9/5 + 32)
print(f"The temperature in Farenheit is: {round(temperature_farenheit, 2)}")

