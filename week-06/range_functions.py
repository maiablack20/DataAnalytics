# Program: range() function examples

# 1. Basic range - start defaults to 0

print("range(5): ")
for i in range(5):
    print(i, end=" ")
print()

# 2. range with start and stop 

print("\nrange(2,8): ")
for i in range(2,8):
    print(i, end=" ")
print()

3. # range with start, stop, and step

print("\nrange(0, 20, 5): ")
for i in range(0, 20, 5):
    print(i, end=" ")
print()

